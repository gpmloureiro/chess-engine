int evaluate(uint64_t pieces[2][6])
{
    int result = 0;

    for (int p = 0; p < 6; p++)
    {
        uint64_t wb = pieces[WHITE][p];
        while (wb)
        {
            int sq = __builtin_ctzll(wb);
            result += PIECE_VALUE[p] + PST[p][sq];
            wb &= wb - 1;
        }
        uint64_t bb = pieces[BLACK][p];
        while (bb)
        {
            int sq = __builtin_ctzll(bb);
            result -= PIECE_VALUE[p] + PST[p][(7 - sq / 8) * 8 + (sq % 8)]; // Mirrored square
            bb &= bb - 1;
        }
    }

    return result;
}